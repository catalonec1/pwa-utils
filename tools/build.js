/* Generates manifest.webmanifest, sw.js and PNG icons for every app.
   Usage: node tools/build.js            (manifests + service workers + icons)
          node tools/build.js --no-icons (skip the browser-rendered icons) */
const fs = require('fs');
const path = require('path');
const { version, apps } = require('./apps');
const ROOT = path.join(__dirname, '..');

function manifest(a) {
  return {
    id: './',
    name: a.name,
    short_name: a.short_name,
    description: a.description,
    lang: 'en',
    dir: 'ltr',
    start_url: './',
    scope: './',
    display: 'standalone',
    display_override: ['standalone', 'minimal-ui'],
    orientation: 'any',
    background_color: '#f6f7fb',
    theme_color: a.color,
    categories: a.categories,
    launch_handler: { client_mode: 'focus-existing' },
    icons: [
      { src: 'icons/icon-192.png', sizes: '192x192', type: 'image/png', purpose: 'any' },
      { src: 'icons/icon-512.png', sizes: '512x512', type: 'image/png', purpose: 'any' },
      { src: 'icons/maskable-512.png', sizes: '512x512', type: 'image/png', purpose: 'maskable' }
    ],
    screenshots: [
      { src: 'icons/screenshot-wide.png', sizes: '1366x768', type: 'image/png', form_factor: 'wide', label: a.name },
      { src: 'icons/screenshot-narrow.png', sizes: '412x915', type: 'image/png', form_factor: 'narrow', label: a.name }
    ]
  };
}

function sw(a) {
  return `/* Generated by tools/build.js — do not edit by hand. */
const CACHE = '${a.id}-v${version}';
const ASSETS = ${JSON.stringify(a.assets)};
self.addEventListener('install', e => {
  e.waitUntil(caches.open(CACHE).then(c => c.addAll(ASSETS)).then(() => self.skipWaiting()));
});
self.addEventListener('activate', e => {
  e.waitUntil(caches.keys().then(keys => Promise.all(
    keys.filter(k => k.startsWith('${a.id}-') && k !== CACHE).map(k => caches.delete(k))
  )).then(() => self.clients.claim()));
});
self.addEventListener('fetch', e => {
  if (e.request.method !== 'GET') return;
  e.respondWith(
    caches.match(e.request, { ignoreSearch: true }).then(hit => hit || fetch(e.request).then(res => {
      if (res.ok && new URL(e.request.url).origin === location.origin) {
        const copy = res.clone();
        caches.open(CACHE).then(c => c.put(e.request, copy));
      }
      return res;
    }).catch(() => caches.match('index.html')))
  );
});
`;
}

function iconSvg(a, size, maskable) {
  const pad = maskable ? 0 : size * 0.06;
  const r = maskable ? 0 : size * 0.22;
  const fs = a.glyph.length > 1 ? size * 0.36 : size * 0.5;
  return `<svg xmlns="http://www.w3.org/2000/svg" width="${size}" height="${size}" viewBox="0 0 ${size} ${size}">
<defs><linearGradient id="g" x1="0" y1="0" x2="1" y2="1"><stop offset="0" stop-color="${a.color}"/><stop offset="1" stop-color="#111827"/></linearGradient></defs>
<rect x="${pad}" y="${pad}" width="${size - 2 * pad}" height="${size - 2 * pad}" rx="${r}" fill="url(#g)"/>
<text x="50%" y="53%" text-anchor="middle" dominant-baseline="middle" font-family="Segoe UI, DejaVu Sans, Arial, sans-serif" font-weight="700" font-size="${fs}" fill="#ffffff">${a.glyph}</text>
</svg>`;
}

async function icons() {
  const { chromium } = require('playwright');
  const browser = await chromium.launch();
  const page = await browser.newPage({ deviceScaleFactor: 1 });
  for (const a of apps) {
    const dir = path.join(ROOT, a.dir, 'icons');
    fs.mkdirSync(dir, { recursive: true });
    const jobs = [['icon-192.png', 192, false], ['icon-512.png', 512, false], ['maskable-512.png', 512, true], ['store-300.png', 300, false]];
    for (const [file, size, mask] of jobs) {
      const svg = iconSvg(a, size, mask);
      fs.writeFileSync(path.join(dir, file.replace('.png', '.svg')), svg);
      await page.setViewportSize({ width: size, height: size });
      await page.setContent(`<html><body style="margin:0;background:transparent">${svg}</body></html>`);
      await page.locator('svg').screenshot({ path: path.join(dir, file), omitBackground: true });
      fs.unlinkSync(path.join(dir, file.replace('.png', '.svg')));
    }
  }
  await browser.close();
}

(async () => {
  for (const a of apps) {
    const dir = path.join(ROOT, a.dir);
    fs.writeFileSync(path.join(dir, 'manifest.webmanifest'), JSON.stringify(manifest(a), null, 2) + '\n');
    fs.writeFileSync(path.join(dir, 'sw.js'), sw(a));
  }
  if (!process.argv.includes('--no-icons')) await icons();
  console.log('built', apps.map(a => a.dir).join(', '));
})().catch(e => { console.error(e); process.exit(1); });
