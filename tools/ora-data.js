/* Generates ora/data.js from an errors.tsv (code, tier F/P, title, cause, fix). Usage: node tools/ora-data.js <errors.tsv> */
const fs = require('fs');
const path = require('path');
const src = process.argv[2];
if (!src) { console.error('usage: node tools/ora-data.js <errors.tsv>'); process.exit(1); }
const rows = fs.readFileSync(src, 'utf8').split(/\r?\n/).filter(Boolean).map(l => {
  const [code, tier, title, cause, fix] = l.split('\t');
  if (!/^(ORA|PLS)-\d{5}$/.test(code) || !/^[FP]$/.test(tier) || !title || !cause || !fix) throw new Error('bad row: ' + l.slice(0, 60));
  return [code, tier === 'F' ? 1 : 0, title, cause, fix];
});
const out = '/* Generated by tools/ora-data.js — do not edit by hand. [code, free(1)/pro(0), title, cause, fix] */\n' +
  '(function (g) { const ORA_DATA = ' + JSON.stringify(rows) + ';\n' +
  "if (typeof module !== 'undefined' && module.exports) module.exports = ORA_DATA; else g.ORA_DATA = ORA_DATA; })(typeof window !== 'undefined' ? window : globalThis);\n";
fs.writeFileSync(path.join(__dirname, '..', 'ora', 'data.js'), out);
console.log(rows.length + ' errors, ' + rows.filter(r => r[1]).length + ' free');
